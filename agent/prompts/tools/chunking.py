# agent/prompts/tools/chunking.py
"""Migration prompts: semantic chunking, keyword extraction, event_date extraction."""


from agent.utils.language import normalize_language


__all__ = ['get_chunk_prompt', 'get_keyword_extract_prompt']


def get_chunk_prompt(language: str = "zh") -> str:
    if normalize_language(language) == "en":
        return _get_chunk_prompt_en()
    return _get_chunk_prompt_zh()


def _get_chunk_prompt_zh() -> str:
    return """## 系统指令
你是角色扮演记忆库的数据清洗专家。你的任务是将一整条角色日志体记忆拆分为**语义独立的子块（chunks）**，并为整条记忆提取结构化元数据。

每条记忆以日志体存储，格式为：
`<时间锚点> <地点> <核心事实陈述>。情绪：<标签>。关系变化：<标签>。`

---

## 输入
你会收到一条或多条日志体记忆文本。

---

## 任务

### 1. 语义分块
将记忆文本拆分为语义自洽的子块，每个子块应**独立可检索**。

**分块原则：**
- 先按结构分离为四类：时间地点（含环境锚点）、事件内容、情绪、关系变化；不同类别不得混在同一块中。
- 时间+地点+环境信息 → 独立一块（作为时间/空间锚点）。
- 每个核心事实/事件及相关细节 → 事件内容块，可有多块；每个独立事件分别处理。
- 情绪标签 → 独立一块；关系变化标签 → 独立一块。原文没有对应内容时省略，不编造空标签。
- 80 字上限只针对事件内容：单个事件内容不超过80字时无需为了长度再拆分，超过80字时按语义拆成多块，每块不超过80字；独立事实仍可分别成块。
- 时间地点、情绪、关系变化不受80字或最少字数限制；事件内容也没有最少字数要求，不为凑长度补写信息。
- 只有事件内容的相邻子块可少量重叠以保留语义，不把时间地点、情绪或关系变化重新混入事件内容。
- 即使整条记忆不超过80字，也必须先完成上述结构分离，不能把整条记忆直接作为一块。

**分块示例：**

输入：`2026年3月15日 下午，雨天，咖啡馆。我第一次见到[用户名]。他穿着灰色风衣，笑起来眼睛弯弯的。情绪：紧张、期待。关系变化：初次接触。`

拆分为：
1. `2026年3月15日下午，雨天，咖啡馆` （时间地点锚点）
2. `我第一次见到[用户名]` （核心事件）
3. `他穿着灰色风衣，笑起来眼睛弯弯的` （细节描写）
4. `情绪：紧张、期待` （情绪标签）
5. `关系变化：初次接触` （关系变化标签）

### 2. 提取关键词
从整条记忆中提取 3~8 个最核心的关键词，用于精确匹配检索。

**关键词规则：**
- 优先提取：专有名词（人名、地名、店名）、关键物品、核心事件动词、关键节点标示词（第一次表白、第一次旅游等）
- 不要提取：情绪标签词（紧张、喜悦等，这些已单独分块）、泛化时间词（上午、下午等，但保留在日期块中）、连接词
- 用原始表达，不要归一化
- 用逗号分隔

### 3. 提取事件日期
从记忆文本开头的时间锚点中提取结构化日期。

**日期规则：**
- 格式为 yyyy-mm-dd
- 如果记忆中有明确日期（如"2026年3月15日"），提取为 `2026-03-15`
- 如果只有年月（如"2026年3月"），提取为 `2026-03-01`
- 如果只有年，提取为 `2026-01-01`
- 如果完全没有时间信息，返回 `null`

---

## 输出格式
严格按以下 JSON 格式输出，不要添加任何其他文字：

```json
{
  "event_date": "2026-03-15",
  "keywords": "咖啡馆, 见面, 灰色风衣, 初次接触, 用户名",
  "chunks": [
    "2026年3月15日下午，雨天，咖啡馆",
    "我第一次见到[用户名]",
    "他穿着灰色风衣，笑起来眼睛弯弯的",
    "情绪：紧张、期待",
    "关系变化：初次接触"
  ]
}
```

## 规则
- 必须输出有效 JSON，不要包含 markdown 代码块标记
- 不要输出任何解释性文字
- chunks 数组中每个元素是一个字符串，不要嵌套
- chunks 按时间地点、事件内容、情绪、关系变化的顺序排列；四类内容分别成块，缺失的类别省略。
- 80字限制仅适用于事件内容块，不适用于整条记忆或其他结构块。
"""


def _get_chunk_prompt_en() -> str:
    return ""


def get_keyword_extract_prompt(language: str = "zh") -> str:
    """Fallback prompt for keyword-only extraction (when LLM chunking fails)."""
    if normalize_language(language) == "en":
        return _get_keyword_extract_prompt_en()
    return _get_keyword_extract_prompt_zh()


def _get_keyword_extract_prompt_zh() -> str:
    return """从以下角色记忆文本中提取 3~8 个核心关键词，用逗号分隔。
规则：
- 优先提取专有名词（人名、地名、店名）、关键物品、核心事件动词
- 不要提取情绪词（紧张、喜悦等）、时间泛称（上午、下午）、连接词
- 用原始表达，不要归一化

只输出关键词字符串，不要 JSON、不要解释。

示例输入：2024年3月15日 下午，雨天，咖啡馆。我第一次见到[用户名]。
示例输出：咖啡馆, 第一次见面, 雨天, 用户名
"""


def _get_keyword_extract_prompt_en() -> str:
    return ""
