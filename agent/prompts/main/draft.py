def get_draft_prompt(character_name: str, language: str = "zh", character_profile: str | None = None) -> str:
    language = normalize_language(language)
    if language == "en":
        return ""
    character_file = (load_character_profile(character_name, language)
                      if character_profile is None else character_profile)

    if language == "zh":
        prompt = _DRAFT_HEADER_ZH + _STYLE_ZH
    else:
        prompt = _DRAFT_HEADER_EN + _STYLE_EN
    prompt += f"""
<character_file>
{character_file}
</character_file>
"""
    return prompt


